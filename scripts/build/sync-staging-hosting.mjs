#!/usr/bin/env node
/**
 * Regenerates the `staging` hosting block in firebase.json from the
 * `biteperk-global` block — the SSOT for how the site is served.
 *
 * Why a generator and not a hand-copied block: firebase.json cannot reference
 * itself, so a staging block is a COPY of the production block, and copies
 * drift — the next cache-header or CSP fix would land on production and leave
 * staging serving something else, which defeats the point of a staging site.
 * `scripts/gates/check-staging-hosting.mjs` fails CI when the two differ, and
 * this script is the fix: run it, commit the result.
 *
 * The staging block differs from production in exactly two ways, both of
 * which this script owns:
 *   - `target: "staging"` (site biteperk-staging, see .firebaserc);
 *   - an `X-Robots-Tag: noindex, nofollow` header on every path. Staging is a
 *     byte-identical copy of the live site (canonicals still point at
 *     biteperk.com, which helps), and a second indexable copy of 190 pages is
 *     the duplicate-content problem this header prevents. Never add this
 *     header to the production block, and never drop it here.
 *
 * Usage: node scripts/build/sync-staging-hosting.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const FILE = process.env.FIREBASE_JSON ?? join(ROOT, "firebase.json");

export const STAGING_TARGET = "staging";
export const NOINDEX_RULE = {
  source: "**",
  headers: [{ key: "X-Robots-Tag", value: "noindex, nofollow" }],
};

/** The staging block derived from a production block — pure, so the gate can call it too. */
export function stagingBlockFrom(production) {
  const block = structuredClone(production);
  block.target = STAGING_TARGET;
  // The production block's "//" note describes biteperk.com; give the copy its own.
  if ("//" in block) block["//"] = "biteperk-staging.web.app \u2014 standing staging copy of the biteperk-global block, GENERATED by scripts/build/sync-staging-hosting.mjs (never hand-edit; noindex on purpose). Deployed from integration by .github/workflows/deploy-staging.yml.";
  block.headers = [...(production.headers ?? []), NOINDEX_RULE];
  return block;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const cfg = JSON.parse(readFileSync(FILE, "utf8"));
  const prod = cfg.hosting.find((h) => h.target === "biteperk-global");
  if (!prod) throw new Error("sync-staging-hosting: no biteperk-global hosting block in firebase.json");
  const next = stagingBlockFrom(prod);
  const i = cfg.hosting.findIndex((h) => h.target === STAGING_TARGET);
  if (i === -1) cfg.hosting.push(next);
  else cfg.hosting[i] = next;
  writeFileSync(FILE, JSON.stringify(cfg, null, 2) + "\n");
  console.log(`sync-staging-hosting: ${i === -1 ? "added" : "updated"} the staging block (${next.headers.length} header rules, ${next.redirects?.length ?? 0} redirects, ${next.rewrites?.length ?? 0} rewrites).`);
}
